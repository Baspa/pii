//! The latency gate's measuring instrument: `POST /analyze` against a
//! **running service**, over a corpus of 2,000-code-point texts, timed from
//! this separate process, reported as a distribution.
//!
//! # What this measures, and what it deliberately does not
//!
//! The clock starts when the request is written and stops when the response
//! body has been fully read. That interval contains the HTTP layer, JSON
//! serialisation on both sides, the rules engine and the model running
//! concurrently, the inference semaphore, and the tokio runtime: that is,
//! everything a caller waits for. An in-process `Instant` around
//! `Model::detect` measures the graph and hides the rest; this binary can
//! take that number too (`--mode in-process`), and it stamps it
//! `transport: in_process` precisely so `gates::evaluate_latency` refuses to
//! turn it into a gate verdict. **The HTTP number is the gate.**
//!
//! # Why the corpus is separate from the benchmark fixture
//!
//! `eval`'s own timing runs over `benchmark/cases/`, whose cases are mostly
//! far shorter than 2,000 characters, and its gate detail said so out loud:
//! *"over the whole fixture (not isolated to 2,000-character inputs)"*. A
//! p95 over that population is a true number about a different question. So
//! the latency corpus is built separately: 200 texts of 2,000 ± 50 **code
//! points**, roughly 33 per gated language, from `benchmark/carriers/`
//! prose, with identifiers spliced in at the density the fixture itself
//! carries: written to a gitignored path and regenerated by command.
//!
//! # Honesty rules this binary follows
//!
//! * **Warm-up is untimed and excluded**, and the count is recorded.
//! * **The distribution is reported, never a mean alone.** `min`, `p50`,
//!   `p95`, `p99`, `max`, mean and standard deviation all travel together.
//! * **The host's load average is sampled throughout the run** and stamped
//!   on the result. `training/reports/latency-investigation.md` §7 is the
//!   reason: on that contended host `min` and `p50` reproduced within 1 ms
//!   across seven runs and `p95` did not, because the tail being measured
//!   was the machine's rather than the model's. A p95 whose host was noisy
//!   is an upper bound, not a measurement.
//! * **The machine is a required field.** A [`LatencyRun`] without a
//!   hardware stamp cannot be serialised at all.
//!
//! # Nothing here prints a text
//!
//! Design section 13. No corpus text, no injected value, no detected span
//! and no response body reaches stdout, a file, or an error message.
//! Everything printed about the work is a count or a millisecond.
//!
//! ```text
//! # regenerate the corpus (gitignored; reads benchmark/ read-only)
//! cargo run --release -p pii-detection-eval --bin latency -- --build-corpus \
//!     --corpus models/latency-corpus.json
//!
//! # measure a running service
//! cargo run --release -p pii-detection-eval --bin latency -- \
//!     --service http://localhost:8202 \
//!     --corpus models/latency-corpus.json \
//!     --concurrency 1 --iterations 1000 --warmup 100 \
//!     --threads 4 --slots 1 \
//!     --hardware "..." --proxy-for "..." \
//!     --out training/reports/latency-<hardware>-<date>.json
//! ```

