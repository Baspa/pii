fn report(run: &LatencyRun, corpus: &Corpus) {
    let budget = pii_detection_eval::gates::LATENCY_P95_MS_MAX;
    println!("{}", run.provenance.command);
    println!(
        "  machine     {} (proxy for: {})",
        run.provenance.hardware, run.provenance.proxy_for
    );
    println!(
        "  transport   {:?}  threads {}  slots {}  concurrency {}",
        run.provenance.transport,
        run.provenance.threads,
        run.provenance.slots,
        run.provenance.concurrency
    );
    println!(
        "  model in the loop: {}   ort: {}",
        run.provenance.model_loaded, run.provenance.ort_version
    );
    println!(
        "  corpus      {} texts, {} code points median ({}..{}), {:.3} identifiers/1000 chars",
        corpus.texts.len(),
        run.chars,
        run.chars_min,
        run.chars_max,
        corpus.identifier_density_per_1000_chars,
    );
    if let Some(shape) = &run.corpus_shape {
        println!(
            "  shape       tokens {}..{} (median {}), windows {}..{} (median {}), padded \
             positions median {} ({} unsplit)",
            shape.tokens_min,
            shape.tokens_max,
            shape.tokens_median,
            shape.windows_min,
            shape.windows_max,
            shape.windows_median,
            shape.padded_positions_median,
            shape.padded_positions_unsplit_median,
        );
        let counts: Vec<String> = shape
            .windows_histogram
            .iter()
            .map(|(windows, texts)| format!("{windows}w:{texts}"))
            .collect();
        println!("  windows     {}", counts.join(" "));
        for (windows, class) in &shape.by_windows {
            println!(
                "  {windows}-window   {} texts, {} real positions, {} padded ({} unsplit), \
                 {:.1}% padding",
                class.texts,
                class.tokens_median,
                class.padded_positions_median,
                class.padded_positions_unsplit_median,
                100.0 * class.padding_waste_fraction,
            );
        }
    }
    let load = &run.provenance.host_load;
    println!(
        "  host load   min {} median {} max {} over {} samples, {} vCPUs",
        fmt_option(load.min),
        fmt_option(load.median),
        fmt_option(load.max),
        load.samples,
        load.host_vcpus,
    );
    print_distribution("  end-to-end ", &run.end_to_end);
    print_histogram("  buckets    ", &run.end_to_end);
    for (windows, distribution) in &run.by_windows {
        print_distribution(&format!("  {windows}-window   "), distribution);
    }
    if let Some(model_only) = &run.model_only {
        print_distribution("  model only ", model_only);
    }
    println!(
        "  warm-up     {} untimed requests, excluded",
        run.provenance.warmup_n
    );
    let verdict = if run.p95_ms <= budget {
        format!(
            "p95 {:.1}ms is INSIDE {budget:.0}ms by {:.1}ms",
            run.p95_ms,
            budget - run.p95_ms
        )
    } else {
        format!(
            "p95 {:.1}ms is OVER {budget:.0}ms by {:.1}ms",
            run.p95_ms,
            run.p95_ms - budget
        )
    };
    println!("  {verdict}");
}

fn print_distribution(label: &str, distribution: &Distribution) {
    println!(
        "{label} n {}  min {:.1}  p50 {:.1}  p95 {:.1}  p99 {:.1}  max {:.1}  (mean {:.1}, sd {:.1})",
        distribution.n,
        distribution.min_ms,
        distribution.p50_ms,
        distribution.p95_ms,
        distribution.p99_ms,
        distribution.max_ms,
        distribution.mean_ms,
        distribution.stddev_ms,
    );
}

fn print_histogram(label: &str, distribution: &Distribution) {
    let buckets: Vec<String> = distribution
        .histogram_10ms
        .iter()
        .map(|(edge, count)| format!("{edge}-{}:{count}", edge + 10))
        .collect();
    println!("{label} {}", buckets.join(" "));
}

fn fmt_option(value: Option<f64>) -> String {
    value.map_or_else(|| "?".to_string(), |value| format!("{value:.2}"))
}

fn write_run(path: &Path, run: &LatencyRun) -> Result<(), Failure> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|_| Failure::Write(path.to_path_buf()))?;
    }
    let json =
        serde_json::to_string_pretty(run).map_err(|error| Failure::Serialise(error.to_string()))?;
    std::fs::write(path, json).map_err(|_| Failure::Write(path.to_path_buf()))
}
