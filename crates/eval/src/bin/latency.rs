const DEFAULT_CORPUS_PATH: &str = "models/latency-corpus.json";
const DEFAULT_CARRIERS_DIR: &str = "benchmark/carriers";
const DEFAULT_CASES_DIR: &str = "benchmark/cases";
const DEFAULT_ITERATIONS: usize = 200;
const DEFAULT_WARMUP: usize = 50;
const DEFAULT_TIMEOUT_SECS: u64 = 30;
const LOAD_SAMPLE_INTERVAL: Duration = Duration::from_millis(500);

const USAGE: &str = "usage:
  latency --build-corpus [--corpus <path>] [--carriers <dir>] [--cases <dir>] [--texts <n>]
  latency --service <url> --hardware <text> --proxy-for <text>
          [--corpus <path>] [--iterations <n>] [--warmup <n>] [--concurrency <n>]
          [--threads <n>] [--slots <n>] [--timeout-secs <n>] [--note <text>]...
          [--mode http|in-process] [--artifact <dir>] [--shape] [--out <path>]";

// ---------------------------------------------------------------------------
// Arguments
// ---------------------------------------------------------------------------

struct Arguments {
    build_corpus: bool,
    corpus: PathBuf,
    carriers: PathBuf,
    cases: PathBuf,
    texts: usize,
    service: Option<String>,
    hardware: Option<String>,
    proxy_for: Option<String>,
    iterations: usize,
    warmup: usize,
    concurrency: usize,
    threads: usize,
    slots: usize,
    timeout_secs: u64,
    transport: Transport,
    artifact: Option<PathBuf>,
    shape: bool,
    out: Option<PathBuf>,
    notes: Vec<String>,
    command: String,
}

fn parse_arguments() -> Result<Arguments, Failure> {
    let raw: Vec<String> = std::env::args().collect();
    let command = raw.join(" ");
    let mut rest = raw.iter().skip(1);

    let mut arguments = Arguments {
        build_corpus: false,
        corpus: PathBuf::from(DEFAULT_CORPUS_PATH),
        carriers: PathBuf::from(DEFAULT_CARRIERS_DIR),
        cases: PathBuf::from(DEFAULT_CASES_DIR),
        texts: latency::DEFAULT_CORPUS_TEXTS,
        service: None,
        hardware: None,
        proxy_for: None,
        iterations: DEFAULT_ITERATIONS,
        warmup: DEFAULT_WARMUP,
        concurrency: 1,
        threads: 0,
        slots: 0,
        timeout_secs: DEFAULT_TIMEOUT_SECS,
        transport: Transport::Http,
        artifact: None,
        shape: false,
        out: None,
        notes: Vec::new(),
        command,
    };

    while let Some(flag) = rest.next() {
        let mut value = || rest.next().cloned().ok_or(Failure::Usage);
        match flag.as_str() {
            "--build-corpus" => arguments.build_corpus = true,
            "--corpus" => arguments.corpus = PathBuf::from(value()?),
            "--carriers" => arguments.carriers = PathBuf::from(value()?),
            "--cases" => arguments.cases = PathBuf::from(value()?),
            "--texts" => arguments.texts = value()?.parse().map_err(|_| Failure::Usage)?,
            "--service" => arguments.service = Some(value()?),
            "--hardware" => arguments.hardware = Some(value()?),
            "--proxy-for" => arguments.proxy_for = Some(value()?),
            "--iterations" => {
                arguments.iterations = value()?.parse().map_err(|_| Failure::Usage)?
            }
            "--warmup" => arguments.warmup = value()?.parse().map_err(|_| Failure::Usage)?,
            "--concurrency" => {
                arguments.concurrency = value()?.parse().map_err(|_| Failure::Usage)?;
            }
            "--threads" => arguments.threads = value()?.parse().map_err(|_| Failure::Usage)?,
            "--slots" => arguments.slots = value()?.parse().map_err(|_| Failure::Usage)?,
            "--timeout-secs" => {
                arguments.timeout_secs = value()?.parse().map_err(|_| Failure::Usage)?;
            }
            "--mode" => {
                arguments.transport = match value()?.as_str() {
                    "http" => Transport::Http,
                    "in-process" => Transport::InProcess,
                    _ => return Err(Failure::Usage),
                }
            }
            "--artifact" => arguments.artifact = Some(PathBuf::from(value()?)),
            "--shape" => arguments.shape = true,
            "--out" => arguments.out = Some(PathBuf::from(value()?)),
            "--note" => arguments.notes.push(value()?),
            _ => return Err(Failure::Usage),
        }
    }

    if arguments.concurrency == 0 || arguments.iterations == 0 {
        return Err(Failure::Usage);
    }
    Ok(arguments)
}

// ---------------------------------------------------------------------------
// Failures. No variant carries a corpus text, a detected value, or a
// response body -- only paths, counts and status codes.
// ---------------------------------------------------------------------------

#[derive(Debug, thiserror::Error)]
enum Failure {
    #[error("{USAGE}")]
    Usage,
    #[error(
        "--service is required to measure, and --hardware and --proxy-for with it: a \
             latency number without the machine that produced it is not a measurement"
    )]
    MissingStamp,
    #[error("corpus: {0}")]
    Corpus(#[from] latency::CorpusError),
    #[error("the corpus at {0} is empty")]
    EmptyCorpus(PathBuf),
    #[error("GET {0}/capabilities was unreachable or did not answer 200")]
    Capabilities(String),
    #[error("POST {service}/analyze answered HTTP {status} on request {nth}")]
    Analyze {
        service: String,
        status: u16,
        nth: usize,
    },
    #[error("POST {service}/analyze was unreachable on request {nth}")]
    Unreachable { service: String, nth: usize },
    #[error("--mode in-process needs --artifact <dir>")]
    MissingArtifact,
    #[error("the artifact at {0} could not be loaded")]
    Artifact(PathBuf),
    #[error("inference failed in-process")]
    Inference,
    #[error("cannot write {0}")]
    Write(PathBuf),
    #[error("the measured run could not be serialised: {0}")]
    Serialise(String),
    #[error("no request was successfully timed")]
    NoSamples,
    #[error("a measuring worker panicked; the run is discarded rather than reported short")]
    WorkerPanicked,
}

// ---------------------------------------------------------------------------
// Wire shapes. Only the fields this binary reads.
// ---------------------------------------------------------------------------

#[derive(Serialize)]
struct AnalyzeRequest<'a> {
    texts: [&'a str; 1],
    /// Serialised through `EntityType`'s own serde rename, so the wire names
    /// this harness sends are the wire names the service defines -- never a
    /// second list of strings that could drift from the enum.
    entities: &'a [EntityType],
    language: &'a str,
}

#[derive(Deserialize)]
struct CapabilitiesResponse {
    entity_types: Vec<EntityType>,
    versions: VersionsResponse,
}

#[derive(Deserialize)]
struct VersionsResponse {
    model: Option<String>,
}

// ---------------------------------------------------------------------------

fn main() {
    match run() {
        Ok(()) => {}
        Err(failure) => {
            eprintln!("latency: {failure}");
            std::process::exit(2);
        }
    }
}

fn run() -> Result<(), Failure> {
    let arguments = parse_arguments()?;

    if arguments.build_corpus {
        let corpus = latency::build_corpus(
            &arguments.carriers,
            &arguments.cases,
            arguments.texts,
            arguments.command.clone(),
        )?;
        latency::write_corpus(&arguments.corpus, &corpus)?;
        println!(
            "built {} texts at {} +/- {} code points (median {}, min {}, max {}), identifier \
             density {:.3} per 1000 chars, into {}",
            corpus.texts.len(),
            corpus.target_chars,
            corpus.tolerance_chars,
            corpus.chars_median(),
            corpus.chars_min(),
            corpus.chars_max(),
            corpus.identifier_density_per_1000_chars,
            arguments.corpus.display(),
        );
        return Ok(());
    }

    let (Some(hardware), Some(proxy_for)) =
        (arguments.hardware.clone(), arguments.proxy_for.clone())
    else {
        return Err(Failure::MissingStamp);
    };
    // `--service` is required to measure over HTTP and meaningless without
    // it; the in-process mode loads the artifact itself and needs no
    // service at all, so demanding one there would only invite someone to
    // point it at a service it is not measuring.
    let service = match (arguments.transport, arguments.service.clone()) {
        (Transport::Http, Some(service)) => service,
        (Transport::Http, None) => return Err(Failure::MissingStamp),
        (Transport::InProcess, service) => service.unwrap_or_default(),
    };

    let corpus = latency::load_corpus(&arguments.corpus)?;
    if corpus.texts.is_empty() {
        return Err(Failure::EmptyCorpus(arguments.corpus.clone()));
    }

    // Over HTTP the model's presence is read from the service itself --
    // `/capabilities` advertising `PERSON` with a model revision beside it
    // -- rather than assumed, because a p95 taken against a rules-only
    // service is not the p95 the gate means and nothing else in the
    // response distinguishes the two. In-process the model is loaded by
    // this binary, so its presence is not in question.
    let (requested, model_loaded) = match arguments.transport {
        Transport::Http => {
            let client = build_client(arguments.timeout_secs);
            let capabilities = read_capabilities(&client, &service)?;
            let loaded = capabilities.entity_types.contains(&EntityType::Person)
                && capabilities.versions.model.is_some();
            (capabilities.entity_types, loaded)
        }
        Transport::InProcess => (Vec::new(), true),
    };

    let (shape, per_text_windows) = if arguments.shape {
        let (shape, windows) = corpus_shape(&corpus, arguments.artifact.as_deref())?;
        (Some(shape), windows)
    } else {
        (None, Vec::new())
    };

    let monitor = LoadMonitor::start();
    let taken = match arguments.transport {
        Transport::Http => measure_http(&arguments, &service, &corpus, &requested)?,
        Transport::InProcess => measure_in_process(&arguments, &corpus)?,
    };
    let host_load = monitor.finish();

    if taken.is_empty() {
        return Err(Failure::NoSamples);
    }

    let by_windows = split_by_windows(&taken, &per_text_windows);
    let samples: Vec<f64> = taken.iter().map(|(_, ms)| *ms).collect();
    let mut run = LatencyRun::from_samples(samples, corpus.chars_median());
    run.chars_min = corpus.chars_min();
    run.chars_max = corpus.chars_max();
    run.corpus_shape = shape;
    run.by_windows = by_windows;
    let run = run.stamp(Provenance {
        transport: arguments.transport,
        hardware: Hardware::new(hardware),
        proxy_for,
        threads: arguments.threads,
        slots: arguments.slots,
        concurrency: arguments.concurrency,
        ort_version: pii_detection_model::runtime_info().to_string(),
        model_loaded,
        warmup_n: arguments.warmup,
        command: arguments.command.clone(),
        measured_unix_secs: latency::unix_secs(),
        host_load,
        notes: arguments.notes.clone(),
    });

    report(&run, &corpus);

    if let Some(path) = arguments.out.as_deref() {
        write_run(path, &run)?;
        println!("wrote {}", path.display());
    }
    Ok(())
}

fn build_client(timeout_secs: u64) -> reqwest::blocking::Client {
    reqwest::blocking::Client::builder()
        .timeout(Duration::from_secs(timeout_secs))
        // One pooled keep-alive connection per worker. TCP setup is
        // therefore paid during warm-up and not in any timed sample, which
        // is the right call for a service behind a load balancer that keeps
        // connections open -- and is stated in the report rather than left
        // for a reader to infer.
        .pool_max_idle_per_host(1)
        .build()
        .unwrap_or_default()
}

fn read_capabilities(
    client: &reqwest::blocking::Client,
    service: &str,
) -> Result<CapabilitiesResponse, Failure> {
    let response = client
        .get(format!("{service}/capabilities"))
        .send()
        .map_err(|_| Failure::Capabilities(service.to_string()))?;
    if !response.status().is_success() {
        return Err(Failure::Capabilities(service.to_string()));
    }
    response
        .json()
        .map_err(|_| Failure::Capabilities(service.to_string()))
}

// ---------------------------------------------------------------------------
// The HTTP measurement
// ---------------------------------------------------------------------------

fn measure_http(
    arguments: &Arguments,
    service: &str,
    corpus: &Corpus,
    requested: &[EntityType],
) -> Result<Vec<(usize, f64)>, Failure> {
    let cursor = Arc::new(AtomicUsize::new(0));
    let endpoint = format!("{service}/analyze");

    // Warm-up, untimed and excluded. It pays for the TCP handshake, the
    // service's first-touch page faults, and any lazily-built regex the
    // rules engine has not compiled yet.
    let warm_client = build_client(arguments.timeout_secs);
    for nth in 0..arguments.warmup {
        let (_, text) = pick(corpus, &cursor);
        one_request(&warm_client, &endpoint, text, requested, nth)?;
    }

    let per_worker = arguments.iterations / arguments.concurrency;
    let remainder = arguments.iterations % arguments.concurrency;
    let mut samples = Vec::with_capacity(arguments.iterations);

    std::thread::scope(|scope| -> Result<(), Failure> {
        let mut handles = Vec::with_capacity(arguments.concurrency);
        for worker in 0..arguments.concurrency {
            let count = per_worker + usize::from(worker < remainder);
            let cursor = Arc::clone(&cursor);
            let endpoint = endpoint.as_str();
            handles.push(scope.spawn(move || -> Result<Vec<(usize, f64)>, Failure> {
                let client = build_client(arguments.timeout_secs);
                let mut mine = Vec::with_capacity(count);
                for nth in 0..count {
                    let (index, text) = pick(corpus, &cursor);
                    let started = Instant::now();
                    one_request(&client, endpoint, text, requested, nth)?;
                    mine.push((index, started.elapsed().as_secs_f64() * 1_000.0));
                }
                Ok(mine)
            }));
        }
        for handle in handles {
            match handle.join() {
                Ok(Ok(mine)) => samples.extend(mine),
                Ok(Err(failure)) => return Err(failure),
                Err(_) => return Err(Failure::WorkerPanicked),
            }
        }
        Ok(())
    })?;

    Ok(samples)
}

/// The next corpus text, round robin, with the index it came from so a
/// sample can be attributed back to the shape of the text that produced it.
fn pick<'a>(corpus: &'a Corpus, cursor: &AtomicUsize) -> (usize, &'a str) {
    let index = cursor.fetch_add(1, Ordering::Relaxed) % corpus.texts.len();
    let text = corpus
        .texts
        .get(index)
        .map(|text| text.text.as_str())
        .unwrap_or_default();
    (index, text)
}

/// Splits samples by the window count of the text each was taken over.
/// Empty when the run had no artifact to window the corpus with -- an
/// unattributed split would be worse than none.
fn split_by_windows(
    taken: &[(usize, f64)],
    per_text_windows: &[usize],
) -> std::collections::BTreeMap<usize, Distribution> {
    let mut grouped: std::collections::BTreeMap<usize, Vec<f64>> =
        std::collections::BTreeMap::new();
    for (index, ms) in taken {
        let Some(windows) = per_text_windows.get(*index) else {
            return std::collections::BTreeMap::new();
        };
        grouped.entry(*windows).or_default().push(*ms);
    }
    grouped
        .into_iter()
        .map(|(windows, samples)| (windows, Distribution::from_samples(samples)))
        .collect()
}

/// One `POST /analyze`, with the response body **fully read** before the
/// caller's clock stops. Reading only the status line would time the
/// service's first byte and not its last, and the gate is what a caller
/// waits for.
fn one_request(
    client: &reqwest::blocking::Client,
    endpoint: &str,
    text: &str,
    requested: &[EntityType],
    nth: usize,
) -> Result<(), Failure> {
    let response = client
        .post(endpoint)
        .json(&AnalyzeRequest {
            texts: [text],
            entities: requested,
            language: "auto",
        })
        .send()
        .map_err(|_| Failure::Unreachable {
            service: endpoint.to_string(),
            nth,
        })?;
    let status = response.status();
    // The body is drained regardless, so the timed interval always covers a
    // complete response.
    let body = response.bytes().map_err(|_| Failure::Unreachable {
        service: endpoint.to_string(),
        nth,
    })?;
    if !status.is_success() {
        return Err(Failure::Analyze {
            service: endpoint.to_string(),
            status: status.as_u16(),
            nth,
        });
    }
    // The body's *length* is all this harness may look at; its content is a
    // list of detected spans. Touched so the read is not optimised away.
    let _ = body.len();
    Ok(())
}

// ---------------------------------------------------------------------------
// The in-process measurement -- informational, and stamped so it cannot be
// mistaken for the gate.
// ---------------------------------------------------------------------------

fn measure_in_process(
    arguments: &Arguments,
    corpus: &Corpus,
) -> Result<Vec<(usize, f64)>, Failure> {
    let dir = arguments
        .artifact
        .as_deref()
        .ok_or(Failure::MissingArtifact)?;
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .enable_all()
        .build()
        .map_err(|_| Failure::Inference)?;

    runtime.block_on(async move {
        let mut config = pii_detection_model::ModelConfig::from_env();
        if arguments.threads > 0 {
            config.intra_threads = arguments.threads;
        }
        if arguments.slots > 0 {
            config.inference_slots = arguments.slots;
        }
        let model = pii_detection_model::Model::load_and_warm(dir, config)
            .await
            .map_err(|_| Failure::Artifact(dir.to_path_buf()))?;

        let cursor = AtomicUsize::new(0);
        for _ in 0..arguments.warmup {
            let (_, text) = pick(corpus, &cursor);
            let document = pii_detection_engine::text::Document::new(text.to_string());
            model
                .detect(&document)
                .await
                .map_err(|_| Failure::Inference)?;
        }

        let mut samples = Vec::with_capacity(arguments.iterations);
        for _ in 0..arguments.iterations {
            let (index, text) = pick(corpus, &cursor);
            let document = pii_detection_engine::text::Document::new(text.to_string());
            let started = Instant::now();
            model
                .detect(&document)
                .await
                .map_err(|_| Failure::Inference)?;
            samples.push((index, started.elapsed().as_secs_f64() * 1_000.0));
        }
        Ok(samples)
    })
}

// ---------------------------------------------------------------------------
// Corpus shape: tokens, windows, padded positions
// ---------------------------------------------------------------------------

/// The corpus's shape, and the per-text window count the run needs to split
/// its samples by. Both come from one windowing pass over the corpus with
/// the shipped tokenizer, so the histogram and the split can never disagree.
fn corpus_shape(
    corpus: &Corpus,
    artifact: Option<&Path>,
) -> Result<(CorpusShape, Vec<usize>), Failure> {
    let dir = artifact.ok_or(Failure::MissingArtifact)?;
    let loaded = pii_detection_model::artifact::Artifact::load(dir)
        .map_err(|_| Failure::Artifact(dir.to_path_buf()))?;
    let windower = pii_detection_model::window::Windower::new(
        &dir.join("tokenizer.json"),
        loaded.manifest.windowing,
    )
    .map_err(|_| Failure::Artifact(dir.to_path_buf()))?;

    let mut tokens = Vec::with_capacity(corpus.texts.len());
    let mut windows = Vec::with_capacity(corpus.texts.len());
    let mut per_text_windows = Vec::with_capacity(corpus.texts.len());
    let mut padded = Vec::with_capacity(corpus.texts.len());
    let mut unsplit = Vec::with_capacity(corpus.texts.len());
    let mut histogram = std::collections::BTreeMap::new();
    #[allow(clippy::type_complexity)]
    let mut classes: std::collections::BTreeMap<usize, (Vec<usize>, Vec<usize>, Vec<usize>)> =
        std::collections::BTreeMap::new();

    for text in &corpus.texts {
        let document = pii_detection_engine::text::Document::new(text.text.clone());
        let built = windower
            .windows(&document)
            .map_err(|_| Failure::Artifact(dir.to_path_buf()))?;
        // Real tokens, counted the way the graph sees them: the number of
        // non-special positions in the first window plus the *new* positions
        // each later window adds.
        let longest = built
            .iter()
            .map(|window| window.input_ids.len())
            .max()
            .unwrap_or(0);
        let total: usize = built.iter().map(|window| window.input_ids.len()).sum();
        tokens.push(total);
        windows.push(built.len());
        per_text_windows.push(built.len());
        // What `Session::infer` actually feeds ONNX, read from the shipped
        // planner rather than from a copy of its rule -- one call per run
        // of equal-length windows, so this is the real-token count and the
        // padding line below reads 0.0%. That is the planner's whole
        // point, not a rounding: see `pii_detection_model::session::batches`.
        //
        // Read from the *local* crate, which is what makes this a
        // statement about the code in this checkout and not about the
        // container under test. Pointing this harness at a service built
        // from different code gives true timings and a shape line
        // describing the wrong planner.
        let fed = pii_detection_model::session::padded_positions(&built);
        // What a single call per document would feed it: batch x the
        // batch's longest window. That is what `Session::infer` did before
        // the trailing-window split, and reporting both is what makes the
        // padding this change removed a number rather than a claim.
        let one_call = built.len() * longest;
        padded.push(fed);
        unsplit.push(one_call);
        *histogram.entry(built.len()).or_insert(0usize) += 1;
        let class = classes.entry(built.len()).or_default();
        class.0.push(total);
        class.1.push(fed);
        class.2.push(one_call);
    }

    tokens.sort_unstable();
    windows.sort_unstable();
    padded.sort_unstable();
    unsplit.sort_unstable();
    let median = |values: &[usize]| values.get(values.len() / 2).copied().unwrap_or(0);

    let by_windows = classes
        .into_iter()
        .map(|(windows, (mut tokens, mut padded, mut unsplit))| {
            tokens.sort_unstable();
            padded.sort_unstable();
            unsplit.sort_unstable();
            let tokens_median = tokens.get(tokens.len() / 2).copied().unwrap_or(0);
            let padded_median = padded.get(padded.len() / 2).copied().unwrap_or(0);
            let waste = if padded_median == 0 {
                0.0
            } else {
                1.0 - tokens_median as f64 / padded_median as f64
            };
            (
                windows,
                pii_detection_eval::latency::WindowClass {
                    texts: tokens.len(),
                    tokens_median,
                    padded_positions_median: padded_median,
                    padded_positions_unsplit_median: unsplit
                        .get(unsplit.len() / 2)
                        .copied()
                        .unwrap_or(0),
                    padding_waste_fraction: waste,
                },
            )
        })
        .collect();

    let shape = CorpusShape {
        texts: corpus.texts.len(),
        tokens_min: tokens.first().copied().unwrap_or(0),
        tokens_median: median(&tokens),
        tokens_max: tokens.last().copied().unwrap_or(0),
        windows_min: windows.first().copied().unwrap_or(0),
        windows_median: median(&windows),
        windows_max: windows.last().copied().unwrap_or(0),
        windows_histogram: histogram,
        padded_positions_median: median(&padded),
        padded_positions_unsplit_median: median(&unsplit),
        by_windows,
    };
    Ok((shape, per_text_windows))
}

// ---------------------------------------------------------------------------
// Host load: sampled throughout, because a p95 taken on a busy machine is
// the machine's tail and not the service's.
// ---------------------------------------------------------------------------

struct LoadMonitor {
    stop: Arc<AtomicBool>,
    handle: Option<std::thread::JoinHandle<Vec<f64>>>,
}

impl LoadMonitor {
    fn start() -> LoadMonitor {
        let stop = Arc::new(AtomicBool::new(false));
        let flag = Arc::clone(&stop);
        let handle = std::thread::spawn(move || {
            let mut observed = Vec::new();
            while !flag.load(Ordering::Relaxed) {
                if let Some(load) = latency::load_average() {
                    observed.push(load);
                }
                std::thread::sleep(LOAD_SAMPLE_INTERVAL);
            }
            observed
        });
        LoadMonitor {
            stop,
            handle: Some(handle),
        }
    }

    fn finish(mut self) -> HostLoad {
        self.stop.store(true, Ordering::Relaxed);
        let mut observed = self
            .handle
            .take()
            .and_then(|handle| handle.join().ok())
            .unwrap_or_default();
        observed.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
        HostLoad {
            samples: observed.len(),
            min: observed.first().copied(),
            median: observed.get(observed.len() / 2).copied(),
            max: observed.last().copied(),
            host_vcpus: std::thread::available_parallelism()
                .map(std::num::NonZeroUsize::get)
                .unwrap_or(0),
        }
    }
}

