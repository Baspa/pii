"""Run the trained checkpoint over Temperate's hand-written PII eval fixture and
score it, as a cheap early read on whether the model is in the right
neighbourhood before building the real benchmark (see
docs/superpowers/plans/2026-08-21-benchmark.md).

WHY THIS IS NOT THE RELEASE BENCHMARK. The 0.9237 PERSON / 0.9877
STREET_ADDRESS F1 reported at the end of training (reports/full-run-cuda.md)
is measured on held-out data generated by the same two synthetic
generators/corpora that produced the training data. That number tells you
whether the model learned what it was shown, not whether it generalises to
text a human actually wrote. This script runs it over 128 hand-written,
deliberately adversarial cases from a different repository
(benchmark/cases) that neither
this model nor Azure has seen, as a first signal only -- 128 cases is small,
and a few points of difference here is noise, not a result.

SCORING RULE (see fixture_scoring.py's module docstring for the full
account, including why an earlier version of this was wrong and reported
0.6711 instead of ~0.91). A must_mask value counts as found (found_all) only
if EVERY occurrence of it in the text has every one of its non-whitespace
characters covered by the union of detected spans -- whitespace between two
adjacent spans is not a leak. A secondary single_span_found figure uses the
old, strict single-span rule. A must_clear value counts as violated if ANY
detected span overlaps it at all.

SPAN MERGING. This script scores the model's output twice: once on the raw
per-window spans the model predicts ("unmerged"), and once after merging
adjacent same-type spans separated only by whitespace
(fixture_scoring.merge_adjacent_whitespace, restricted to PERSON and
STREET_ADDRESS -- see that function's docstring for why). Merging is
expected to raise the single-span figure (an entity now comes back as one
span instead of two or three) without changing found_all recall (union
coverage already counted whitespace-separated spans as non-leaking before
merging ever ran).

DECODING REUSES align.py, NOT A SECOND BIO DECODER. The model was trained
with max_length=256, stride=32 against the xlm-roberta-base fast tokenizer's
offset_mapping (see align.py's docstring and train.py's build_arg_parser
defaults). Inference here calls the exact same tokenize_and_align() for
windowing and the exact same reconstruct_spans() for decoding predicted
label ids back to character spans -- with entities=[] (there is no gold
label for hand-written fixture text), which makes tokenize_and_align's own
label pass mark every real token "O" and every special/pad token
IGNORE_INDEX. That IGNORE_INDEX mask is reused as-is to blank out special
tokens' predictions before reconstruction, so windowing, special-token
detection and span reconstruction are 100% align.py's logic, never
reimplemented here.

SCORING AN ONNX GRAPH INSTEAD OF THE CHECKPOINT. `--onnx PATH` swaps the
forward pass for an onnxruntime InferenceSession and changes nothing else:
same tokenize_and_align windowing, same reconstruct_spans decode, same
fixture_scoring rules. Running the checkpoint and its exported graph over
the same fixture is the only way to state what quantisation cost in the
terms the service actually cares about -- spans, per language -- rather
than in token-position agreement. A held-out score cannot do this: the
merged-name retrain scored 0.9940 on its own split while losing four
German values that this fixture caught at once (reports/
retrained-comparison.md), so the control has to be run beside the subject
on text neither of them was trained on.

Usage:
    python eval_fixture.py \
        --checkpoint runs/full \
        --fixture ../benchmark/cases \
        --out reports/model-fixture-2026-08-21.json

    python eval_fixture.py --onnx ../models/staging/model.onnx \
        --fixture ../benchmark/cases \
        --out reports/model-int8-fixture-2026-08-22.json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import torch
from transformers import AutoTokenizer, BertForTokenClassification

from align import IGNORE_INDEX, reconstruct_spans, tokenize_and_align
from fixture_scoring import (
    DEFAULT_FIXTURE,
    MERGEABLE_TYPES,
    load_cases,
    merge_adjacent_whitespace,
    print_summary,
    score_case,
    summarize,
)

TOKENIZER_NAME = "FacebookAI/xlm-roberta-base"


def _merge_touching_typed(typed_spans: list[tuple[int, int, str]]) -> list[tuple[int, int, str]]:
    """Stitch together touching/overlapping SAME-type spans -- the plumbing
    needed because tokenize_and_align windows long text with a stride, so
    one entity near a window boundary can be reconstructed as two
    back-to-back spans from two overlapping windows. This is not the
    task's span-merging feature (that's merge_adjacent_whitespace, applied
    separately below); it never bridges a whitespace gap, only spans that
    already touch or overlap. Different-type touching spans are left apart
    (safer than guessing which type is right)."""
    if not typed_spans:
        return []
    ordered = sorted(typed_spans)
    merged = [list(ordered[0])]
    for s, e, t in ordered[1:]:
        ps, pe, pt = merged[-1]
        if t == pt and s <= pe:
            merged[-1][1] = max(pe, e)
        else:
            merged.append([s, e, t])
    return [(s, e, t) for s, e, t in merged]


def torch_predictor(checkpoint: str, device: str):
    """Per-window predicted label ids from the PyTorch checkpoint."""
    model = BertForTokenClassification.from_pretrained(checkpoint)
    model.to(device)
    model.eval()

    @torch.no_grad()
    def predict(window) -> list[int]:
        input_ids = torch.tensor([window.input_ids], device=device)
        attention_mask = torch.tensor([window.attention_mask], device=device)
        logits = model(input_ids=input_ids, attention_mask=attention_mask).logits
        return logits.argmax(-1)[0].tolist()

    return predict


def onnx_predictor(onnx_path: str):
    """Per-window predicted label ids from an exported ONNX graph.

    The ONLY difference from torch_predictor is the forward pass. Windowing
    is still align.tokenize_and_align, decoding is still
    align.reconstruct_spans and scoring is still fixture_scoring, so a
    difference between the two runs is a difference between the two
    runtimes and cannot be a difference between two decoders. That is the
    whole point of scoring the graph here rather than writing a second
    evaluation script for it.

    token_type_ids is all zeros -- single-sequence token classification.
    PyTorch defaults it to zeros internally; ONNX has no default, so it is
    passed explicitly. CPUExecutionProvider is pinned because the
    deployment target is CPU-only and because another provider would make
    this a measurement of that provider rather than of the export.
    """
    import numpy as np
    import onnxruntime as ort

    session = ort.InferenceSession(onnx_path, providers=["CPUExecutionProvider"])

    def predict(window) -> list[int]:
        input_ids = np.asarray([window.input_ids], dtype=np.int64)
        logits = session.run(
            ["logits"],
            {
                "input_ids": input_ids,
                "attention_mask": np.asarray([window.attention_mask], dtype=np.int64),
                "token_type_ids": np.zeros_like(input_ids),
            },
        )[0]
        return logits.argmax(-1)[0].tolist()

    return predict


def predict_spans(
    text: str,
    tokenizer,
    predict,
    max_length: int,
    stride: int,
) -> list[tuple[int, int, str]]:
    """(start, end, type) spans the model predicts as PII in `text`, stitched
    across windows (see _merge_touching_typed) but NOT whitespace-merged --
    that is a separate, optional step callers apply themselves. entities=[]
    below means tokenize_and_align's own label pass produces "O" for every
    real token and IGNORE_INDEX for every special token -- exactly the mask
    this function needs to blank out special-token predictions before
    reconstruct_spans, without writing that logic twice.

    `predict` is a callable(window) -> per-token label ids: either
    torch_predictor's or onnx_predictor's. Everything either side of it is
    shared."""
    windows = tokenize_and_align(text, [], tokenizer, max_length, stride)
    raw_spans: list[tuple[int, int, str]] = []
    for w in windows:
        pred_ids = predict(w)
        decode_ids = [
            IGNORE_INDEX if gold == IGNORE_INDEX else pred
            for pred, gold in zip(pred_ids, w.labels)
        ]
        for start, end, entity_type in reconstruct_spans(w.offset_mapping, decode_ids):
            raw_spans.append((start, end, entity_type))
    return _merge_touching_typed(raw_spans)


def warn(message: str) -> None:
    print(f"WARNING: {message}", file=sys.stderr)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    source = ap.add_mutually_exclusive_group()
    source.add_argument("--checkpoint", default=None, help="directory holding the trained checkpoint")
    source.add_argument("--onnx", default=None, help="an exported ONNX graph, scored instead of the checkpoint")
    ap.add_argument(
        "--fixture",
        default=DEFAULT_FIXTURE,
        help="pii-eval-cases.json, or a directory of case arrays such as ../benchmark/cases (read-only, never modified)",
    )
    ap.add_argument("--max-length", type=int, default=256, help="must match training (see train.py's default)")
    ap.add_argument("--stride", type=int, default=32, help="must match training (see train.py's default)")
    ap.add_argument("--device", default="cpu", choices=["cpu", "cuda", "mps"])
    ap.add_argument("--out", default=None, help="path to write detailed per-case JSON results")
    args = ap.parse_args()

    if args.onnx:
        predict = onnx_predictor(args.onnx)
        model_kind, model_path = "onnx", args.onnx
    else:
        checkpoint = args.checkpoint or "runs/full"
        predict = torch_predictor(checkpoint, args.device)
        model_kind, model_path = "checkpoint", checkpoint

    tokenizer = AutoTokenizer.from_pretrained(TOKENIZER_NAME, use_fast=True)

    cases = load_cases(args.fixture)
    results_unmerged = []
    results_merged = []
    for case in cases:
        typed_spans = predict_spans(case["text"], tokenizer, predict, args.max_length, args.stride)
        unmerged_spans = [(s, e) for s, e, _t in typed_spans]
        merged_typed = merge_adjacent_whitespace(case["text"], typed_spans)
        merged_spans = [(s, e) for s, e, _t in merged_typed]
        results_unmerged.append(score_case(case, unmerged_spans, warn))
        results_merged.append(score_case(case, merged_spans, warn))

    summary_unmerged = summarize(results_unmerged)
    summary_merged = summarize(results_merged)

    command = "python " + " ".join(sys.argv)
    output = {
        "command": command,
        # "checkpoint" is kept under its original name whatever produced the
        # run, so compare_fixture.py and eval_fixture_rules.py keep reading
        # the same key; "model_kind" says which of the two it names.
        "checkpoint": model_path,
        "model_kind": model_kind,
        "fixture": args.fixture,
        "max_length": args.max_length,
        "stride": args.stride,
        "merge_types": sorted(MERGEABLE_TYPES),
        "n_cases": len(cases),
        # "summary"/"cases" alias the MERGED variant -- what a real
        # deployment would mask after span merging. Both variants are also
        # kept explicitly so the effect of merging is visible rather than
        # baked in (see fixture-comparison.md).
        "summary": summary_merged,
        "cases": results_merged,
        "summary_unmerged": summary_unmerged,
        "cases_unmerged": results_unmerged,
        "summary_merged": summary_merged,
        "cases_merged": results_merged,
    }

    if args.out:
        Path(args.out).write_text(json.dumps(output, indent=2, ensure_ascii=False))
        print(f"Wrote {args.out}")

    print("=== Unmerged (raw model spans) ===")
    print_summary(summary_unmerged)
    print("=== Merged (adjacent same-type spans joined across whitespace) ===")
    print_summary(summary_merged)


if __name__ == "__main__":
    main()
